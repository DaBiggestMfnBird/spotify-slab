#!/usr/bin/env bun
/**
 * Subset Barlow to the characters the panel can show and write it out as a TS
 * module of base64 woff2 faces, so the single-file extension carries its type.
 *
 * Basic Latin stays whole because device names come from the user. Anything
 * outside it falls through to the stack in styles.ts.
 *
 *   bun run gen:fonts
 */

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import subsetFont from "subset-font";

const root = join(import.meta.dir, "..");
const out = join(root, "src/ui/fonts.generated.ts");

const FACES = [
    { family: "SLAB Barlow", pkg: "barlow-semi-condensed", weight: 500 },
    { family: "SLAB Barlow", pkg: "barlow-semi-condensed", weight: 600 },
    { family: "SLAB Barlow", pkg: "barlow-semi-condensed", weight: 700 },
    { family: "SLAB Barlow Tall", pkg: "barlow-condensed", weight: 700 },
];

// The tall cut only sets the BPM figure, so it gets digits and nothing else.
const TEXT = Array.from({ length: 95 }, (_, index) => String.fromCharCode(32 + index)).join("") + "−–’‘“”…";
const TALL_TEXT = "0123456789.–";

let css = "";
let total = 0;
for (const face of FACES) {
    const path = join(root, "node_modules/@fontsource", face.pkg, "files", `${face.pkg}-latin-${face.weight}-normal.woff2`);
    const source = await readFile(path);
    const subset = await subsetFont(source, face.family.endsWith("Tall") ? TALL_TEXT : TEXT, {
        targetFormat: "woff2",
    });
    total += subset.length;
    css +=
        `@font-face{font-family:"${face.family}";font-weight:${face.weight};font-style:normal;font-display:swap;` +
        `src:url(data:font/woff2;base64,${subset.toString("base64")}) format("woff2")}\n`;
    console.log(`${face.pkg} ${face.weight}: ${(subset.length / 1024).toFixed(1)} kB`);
}

await writeFile(
    out,
    `// Generated by scripts/gen-fonts.ts. Barlow is SIL OFL 1.1, see the README.\nexport const FONT_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`fonts.generated.ts: ${(total / 1024).toFixed(1)} kB of woff2`);
